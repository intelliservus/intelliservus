-- Up Migration
-- 应用角色：非超级用户，使 RLS 对应用连接真正生效（超级用户会绕过 RLS）。
-- 迁移与运维仍使用所有者账号；应用在事务内 SET LOCAL ROLE 切换到本角色。

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'saas_app') THEN
    CREATE ROLE saas_app NOLOGIN;
  END IF;
END
$$;

GRANT USAGE ON SCHEMA iam, tenant, audit, public TO saas_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA iam, tenant, audit TO saas_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA iam, tenant, audit TO saas_app;

-- 之后新增的表默认也要授权；缺省权限只影响后续由同一角色创建的对象。
ALTER DEFAULT PRIVILEGES IN SCHEMA iam GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO saas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA tenant GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO saas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA audit GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO saas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA iam GRANT USAGE, SELECT ON SEQUENCES TO saas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA tenant GRANT USAGE, SELECT ON SEQUENCES TO saas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA audit GRANT USAGE, SELECT ON SEQUENCES TO saas_app;

-- Down Migration

ALTER DEFAULT PRIVILEGES IN SCHEMA audit REVOKE USAGE, SELECT ON SEQUENCES FROM saas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA tenant REVOKE USAGE, SELECT ON SEQUENCES FROM saas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA iam REVOKE USAGE, SELECT ON SEQUENCES FROM saas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA audit REVOKE SELECT, INSERT, UPDATE, DELETE ON TABLES FROM saas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA tenant REVOKE SELECT, INSERT, UPDATE, DELETE ON TABLES FROM saas_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA iam REVOKE SELECT, INSERT, UPDATE, DELETE ON TABLES FROM saas_app;
REVOKE USAGE, SELECT ON ALL SEQUENCES IN SCHEMA iam, tenant, audit FROM saas_app;
REVOKE SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA iam, tenant, audit FROM saas_app;
REVOKE USAGE ON SCHEMA iam, tenant, audit, public FROM saas_app;
DROP ROLE IF EXISTS saas_app;
